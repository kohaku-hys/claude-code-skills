def is_person(noun):
    return bool(PERSON_RE.search(noun))


def is_abstract(noun):
    """抽象的な物か（上の一覧の語で終わる・「〜案」・「〜性」・時間）。人・物・薬・物質・建物・知らない語は False"""
    if not noun or noun in ('女性', '男性', '異性'):
        return False
    if noun == EVENT_NOUN:                                      # 節（出来事・行い）を主語にした「〜のが」
        return True
    if is_time(noun):
        return True
    if noun.endswith(ABSTRACT_NOUNS) or noun.endswith('()'):    # 〜() はプログラムの関数（計算機の中の物）
        return True
    if noun.endswith('案') and not noun.endswith(PAPER_NOUNS):   # 提案・改善案（考えの案）。答案・図案は紙・図の物
        return True
    return len(noun) >= 2 and noun.endswith('性')


def is_placeholder(noun):
    """「どの〜か」を書かないと中身が決まらない抽象語か（設計・前提・判断・品質・議論・関係・問題の類）。
    データ・値・結果のような量、測定・現象の概念、名指しした性質（線形・対称）は、名指しした物として False"""
    if noun.endswith('案') and not noun.endswith(PAPER_NOUNS):
        return True
    return bool(noun) and noun.endswith(PLACEHOLDER_NOUNS)


def compound_head(noun):
    """複合語の前の部分（「鉄骨構造」→ 鉄骨・「設計判断」→ 設計・「線形性」→ 線形・「改善案」→ 改善）。
    語全体が一覧の語（「前提」「方向性」）か、一覧の語で終わらない語なら ''"""
    ends = [w for w in DUAL_NOUNS + ABSTRACT_NOUNS if noun.endswith(w)]
    if ends:
        return noun[:-len(max(ends, key=len))]
    if len(noun) >= 2 and noun.endswith(('案', '性')):
        return noun[:-1]
    return ''


def abstract_arg(noun, mod, by_modifier=False):
    """主語・目的語 (名詞, 「〜の」の前の名詞) が抽象的な物か。
    両方の意味がある語（土台・解像度・構造）は、複合語の前の部分か「〜の」の前の語で決める（鉄骨構造・町家の土台＝物）。
    by_modifier=True（崩れる）は、崩れる物が「〜の」の前の語か複合語の前の部分で名指しされていれば、その語で決める。
      名指しした語が専門の語・物の名前・量（集中定数・抵抗値・測定結果・線形）なら、何が成り立たなくなるかが1通りに決まるので拾わない
      （「1GHzでは集中定数の前提が崩れる」「抵抗値のバランスが崩れると」「線形性が崩れ」）。
      名指しした語そのものが設計・前提・判断・議論・関係の類（「戦略の根拠」「設計判断」）なら、どれのことか決まらないので拾う"""
    if noun.endswith(DUAL_NOUNS):
        return is_abstract(compound_head(noun) or mod)
    if by_modifier:
        named = mod or compound_head(noun)
        if named:
            return is_placeholder(named)
    return is_abstract(noun)


def in_quote(text, start, end):
    """text[start:end] が「」『』の中に丸ごと入っているか。人の言葉・語を引いて論じる文は書き手の文ではないので拾わない
    （「「結局は慣れに他ならない」と先生は言った。」「「単なる道具ではない」という言い方は使わない。」）"""
    for o, c in (('「', '」'), ('『', '』')):
        i = text.rfind(o, 0, start)
        if i < 0 or text.find(c, i, start) >= 0:
            continue
        j = text.find(c, start)
        if j >= end:
            return True
    return False


