#   「〜を、」の後に主文の主語「〜が」が来る語順だけ拾う。次の物は拾わない:
#   ・が の前がひらがな（「変えながら」「測ったが」）＝が は主語の助詞ではない
#   ・が の後に従属節の印が来る（〜ように・〜まで・範囲・ため・「〜」の名詞・連体形＋名詞）＝が は従属節の主語
#     （「周波数を、出力電圧が最大になるように調整した。」「入力を、出力が飽和しない範囲で変えた。」）
#   ・が の後に時の従属節（〜てから・〜と・〜ずに・〜うちに・〜前に・〜後に）が来る
#     （「試料を、温度が下がってから取り出した。」「この処理を、二つのタスクが行うと…」教員の資料）。
#     条件の「と」は、語を入れ替えた反復の CONDITION_RE と同じ形（と＋い・し・言・思・考 は引用の「と」）
TAME_RE = re.compile(r'^[^、。「」\n]{1,4}を[、,][^、。「」\n]{0,8}?[' + NOUN + ']が')
SUBORDINATE_RE = re.compile(r'よう|まで|ため|とき|時に|場合|範囲|ので|のに|ても|でも|れば|たら|なら|」の|'
                            r'[てで]から|[うくぐすつぬぶむるたい]と(?![いし言思考])|ずに|うちに|(?<![最直以])(?:前|後)に|'
                            r'(?:[るたい]|ない)[' + NOUN + ']')


def tame_match(sentence):
    m = TAME_RE.match(sentence)
    if not m:
        return ''
    if SUBORDINATE_RE.search(sentence[m.end():]):
        return ''
    return m.group(0)


