# 箇条書きの記号・番号（行の頭）。この後ろを文の頭として見る
BULLET_RE = re.compile(r'^[ \t\u3000]*(?:[・\-*•■□●○◆◇▶▸►]|\d+[.)．）]|[（(]\d+[)）]|[①-⑳])?[ \t\u3000]*')
# 文の頭（接続語＋読点の後も文の頭）に置いた予告「重要なのは、」「結論から言うと、」。
#   分裂文の評価の語（重要な・面白い・興味深い・注目したい・特筆すべき・見逃せない）＋「のは・ことは・点は」と、
#   主文の前に話し方を言う「結論から・端的に・一言で・正直に 言うと」。副詞の枠（何より・特に）は文章用の検査器（別スキル）と同じ。
#   2026-10-01 3回目に「何より」「興味深い・注目したい・特筆すべき・見逃せない」「重要な点は」「正直に言うと」を足した
#   （yomiyasu の slop-catalog の前置フィラー「正直に言うと」「ここで注目すべきは」）。
#   2026-10-01 4回目に足した（試験集 preface-hit-25〜27・39。文章用の検査器（別スキル・このリポジトリには含まれない） の PREFACE_RE と同じ型）:
#   ・話し方の前置き「正直なところ、」「本音を言えば」「実を言うと」（正直に言うと と同じ、主文の前に話し方を言う形）
#   ・「肝は、」「カギは、」「鍵になるのは、」（体の部分・道具を「要の所」に見立てた比喩の名詞で、主文を予告する形。読点が付く形だけ。
#     分裂文と同じく、後ろが名詞・こと・だ で終わる時だけ。「鍵は、机の上にある」は予告ではない）。
#     「ポイントは、」は比喩でない普通の語で、教員のスライド「ポイントは、電気抵抗率！」（ある授業の第2回）に当たったので入れない
PREFACE_RE = re.compile(
    r'^(?:(?:だが|しかし|そして|また|ただ|でも|さて|なお|一方で?|つまり|実は|ところが)[、,]?)?'
    r'(?:まず|ここで|特に|最も|一番|いちばん|本当に|何より(?:も)?|なにより(?:も)?)?'
    r'(?:(?P<cleft>(?:(?:重要|大事|大切|肝心|厄介)な|避けたい|面白い|おもしろい|興味深い|注目(?:すべき|したい)|'
    r'特筆すべき|見逃せない)(?:の|こと|点)は|(?:注目|特筆)すべき点?は|'
    r'(?:カギ|鍵|肝|キモ)(?:[とに]なる(?:の|こと))?は(?=[、,]))'
    r'|(?:結論から|端的に|一言で|正直に|本音を|実を|本当のことを)(?:言う|いう|言え|いえ|申し上げる|申し上げれ)(?:と|ば)'
    r'|正直なところ(?=[、,]))')
# 「重要なのは、Xである。」の形（分裂文）は、「〜のは」の後の最初の切れ目（かっこの外の読点・句点）が名詞か「だ・である・で」で終わる
#   （「重要なのは「自明解だけか、それとも非自明な解もあるか」で、これも階数だけで決まります。」も分裂文）。
#   「重要なのはどれか、班で話し合った。」「大事なのは分かっているが、」は動詞・問いで切れるので予告ではない
CLEFT_END_RE = re.compile(r'(?:だ|である|です|だった|であった|でした|ではない|でない|ではなく|でなく|で|であり|'
                          r'こと|もの|ところ|ため|[' + NOUN + '」』）)%％])$')


def first_clause(text):
    """かっこの外で最初の読点・句点までを返す"""
    depth = 0
    for i, ch in enumerate(text):
        if ch in '「『（(':
            depth += 1
        elif ch in '」』）)':
            depth = max(0, depth - 1)
        elif ch in '、,。' and depth == 0:
            return text[:i]
    return text


def preface_match(sentence):
    """AIK1 文の頭の予告を返す（無ければ ''）"""
    body = BULLET_RE.sub('', sentence, count=1)
    m = PREFACE_RE.match(body)
    if not m:
        return ''
    if m.group('cleft'):
        rest = re.sub(r'^[、,\s]+', '', body[m.end():])
        if not CLEFT_END_RE.search(first_clause(core(rest)).strip()):
            return ''
    return m.group(0)


