OCR_RUN_RE = re.compile('(?<=[ぁ-んァ-ヺ一-龥「」])' + OCR_PUNCT + '{2,}|' + OCR_PUNCT + '{2,}(?=[ぁ-んァ-ヺ一-龥「」])')


def ocr_noise(line):
    """1行に OCR の崩れの印（上の2つ）があるか"""
    if OCR_TILDE_RE.search(line):
        return True
    for m in OCR_RUN_RE.finditer(line):
        run = m.group(0)
        if run.strip('.') and run != '~~':      # 点だけ・取り消し線は人が打つ
            return True
    return False


def ocr_noise_near(lines, k):
    """lines[k] か、すぐ前・すぐ後の空でない行に OCR の崩れの印があるか"""
    near = [lines[k]]
    j = k - 1
    while j >= 0 and not lines[j].strip():
        j -= 1
    if j >= 0:
        near.append(lines[j])
    j = k + 1
    while j < len(lines) and not lines[j].strip():
        j += 1
    if j < len(lines):
        near.append(lines[j])
    for line in near:
        if ocr_noise(line):
            return True
    return False


def line_around(text, start, end):
    """text[start:end] を含む行と、行の頭から start までを返す"""
    ls = text.rfind('\n', 0, start) + 1
    le = text.find('\n', end)
    if le < 0:
        le = len(text)
    return text[ls:le], text[ls:start]


def emoji_is_mark(text, start, end):
    """絵文字の当たりが、絵でなく記号の形として使った物か（上の3つと OCR の崩れの行）"""
    line, head = line_around(text, start, end)
    if text[start] in MONO_SHAPE_EMOJI and not head.strip(SPACES):
        return True                              # 行の頭の ⚫ は箇条書きの印
    if SHAPE_ONLY_LINE_RE.match(line):
        return True                              # 形だけの行は図の中の印
    if GARBLED_RE.search(line):
        return True                              # 文字化けの行
    return ocr_noise_near(text.split('\n'), text.count('\n', 0, start))   # OCR の崩れの行


