KADAI_HEADING_RE = re.compile(r'\d+(?:\.\d+)*\s*(?:検討)?課題\s*\d+')


def in_kadai_heading(body, pos):
    """「5.7 検討課題7　…」の見出しの行か。見出しは資料の問題文の写しなので、書き手の文として数えない
    （2026-10-13 テーマ1: 本人指示で問題文どおりにした見出しの「…ことを示している」が P-025 に掛かった）"""
    start = body.rfind('\n', 0, pos) + 1
    return bool(KADAI_HEADING_RE.match(body, start))


def check_text(body):
    findings = []
    for pattern, suggestion, pid in AI_PATTERNS:
        for m in re.finditer(pattern, body):
            if in_kadai_heading(body, m.start()):
                continue
            # マッチ箇所の前後30文字を抜粋
            start = max(0, m.start() - 20)
            end = min(len(body), m.end() + 20)
            ctx = body[start:end].replace('\n', ' ')
            findings.append({
                'pid': pid,
                'rule': pid,
                'match': m.group(0),
                'suggest': suggestion,
                'context': ctx,
            })

    # P-039 一致表現の反復(密度)チェック
    dens_hits = []
    for rgx in AGREEMENT_FAMILY:
        dens_hits += [m.group(0) for m in re.finditer(rgx, body)]
    if len(dens_hits) > AGREEMENT_THRESHOLD:
        findings.append({
            'pid': 'P-039',
            'rule': 'P-039',
            'match': f'一致表現の反復 {len(dens_hits)}回（自然なのは{AGREEMENT_THRESHOLD}回まで）',
            'suggest': '一致の言明は各節で1回に集約し、具体例は数字だけ示す。検出語: ' + '・'.join(dens_hits),
            'context': '（本文全体の密度チェック）',
        })

    # P-066 括弧で添えた出典の密度チェック
    cites = [m.group(0) for m in CITE_PAREN_RE.finditer(body)]
    if len(cites) > CITE_PAREN_THRESHOLD:
        findings.append({
            'pid': 'P-066',
            'rule': 'P-066',
            'match': f'括弧で添えた出典 {len(cites)}個（自然なのは{CITE_PAREN_THRESHOLD}個まで）',
            'suggest': '文の流れで出所が分かる所の（表N）（N節）は外す。根拠に使う参照は「表6で」「4.3節では」と文の中で書く。検出: ' + '・'.join(cites[:10]),
            'context': '（本文全体の密度チェック）',
        })

    # AIK（AI臭い文章の3特徴）のうち、正規表現1本の物。「」『』で引いた語は書き手の文ではないので外す
    for rule, pid, rx, suggestion in AIK_PATTERNS:
        for m in rx.finditer(body):
            if in_quote(body, m.start(), m.end()):
                continue
            # 絵文字の字でも、箇条書きの印・図の印・文字化けは絵ではない（emoji_is_mark）
            if rule == 'emoji' and emoji_is_mark(body, m.start(), m.end()):
                continue
            start = max(0, m.start() - 20)
            end = min(len(body), m.end() + 20)
            findings.append({
                'pid': pid,
                'rule': rule,
                'match': m.group(0),
                'suggest': suggestion,
                'context': body[start:end].replace('\n', ' '),
            })

    # AIK のうち、行・文ごとに見る物
    findings += yokoi_findings(body)
    return findings


def print_reference(refs):
    """参考層の指摘を表示する（exit には数えない）"""
    if not refs:
        return
    print(f'\n[参考] 合否に数えない指摘 {len(refs)} 件（読んで、直すかを決める）:')
    for f in refs[:5]:
        print(f'  {f["pid"]} {f["match"]}: 「{f["context"]}」 → 候補: {f["suggest"]}')
    if len(refs) > 5:
        print(f'  ... 他 {len(refs) - 5} 件')


