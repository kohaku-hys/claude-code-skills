# 測定・現象の概念（2026-10-01 3回目に追加）。実験レポートで比喩の動詞と組むと、何をしたかが1通りに決まらない
#   （「誤差を1つずつ潰した」「この現象を深掘りした」「回路の挙動を紐解く」「配線抵抗の影響が後から効いてくる」）
MEASURE_NOUNS = ('誤差', '現象', '挙動', '特性', '傾向', '影響', '効果', '変化', 'ばらつき', 'ずれ', 'ズレ', '差', '測定')
ABSTRACT_NOUNS = DATA_NOUNS + PLACEHOLDER_NOUNS + MEASURE_NOUNS
# ひらがなを含む抽象語（名詞の字の続きだけでは取れないので、終わりの一致で取る）
KANA_ABSTRACT = tuple(w for w in ABSTRACT_NOUNS if re.search('[ぁ-ん]', w))
